-- V5: shopping carts.
--
-- One cart per user, created lazily on first use and reused thereafter. The
-- unique constraint on user_id is what makes "get or create my cart" safe under
-- concurrent requests: two simultaneous first-adds race, one inserts, the other
-- gets a constraint violation and re-reads.
--
-- NOTE ON PRICES
-- Cart items store ONLY product_id and quantity — never a price. Prices are
-- resolved from the catalogue every time the cart is read or an order is placed.
-- Two consequences, both intended:
--   * a client cannot influence what anything costs; there is no price field to
--     tamper with, anywhere in the cart API;
--   * a catalogue price change is reflected in the cart immediately, which is
--     the behaviour a shopper expects before checkout.
-- The price is frozen only at checkout, into order_items (see V6).

CREATE TABLE carts (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uq_carts_user ON carts (user_id);

CREATE TABLE cart_items (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT      NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    quantity   INTEGER     NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0,

    CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0 AND quantity <= 999)
);

-- Adding a product already in the cart increments the existing line rather than
-- creating a second one. This constraint is what makes that invariant hold even
-- if two "add to cart" requests arrive simultaneously.
CREATE UNIQUE INDEX uq_cart_items_cart_product ON cart_items (cart_id, product_id);

CREATE INDEX idx_cart_items_cart ON cart_items (cart_id);

COMMENT ON TABLE  cart_items          IS 'Cart lines. Deliberately store no price — prices come from the catalogue at read time.';
COMMENT ON COLUMN cart_items.quantity IS 'CHECK (quantity > 0) makes a zero or negative line impossible; 999 caps accidental or hostile input.';
