-- V3: product catalogue.

CREATE TABLE categories (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    slug        VARCHAR(80)  NOT NULL,
    description VARCHAR(500) NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT ck_categories_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_categories_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

-- Case-insensitive name uniqueness: "Electronics" and "electronics" are the
-- same category to a human, so they must be the same category to the database.
CREATE UNIQUE INDEX uq_categories_name_lower ON categories (lower(name));
CREATE UNIQUE INDEX uq_categories_slug       ON categories (slug);

COMMENT ON TABLE categories IS 'Product categories. Administrator-managed.';


CREATE TABLE products (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(64)   NOT NULL,
    name        VARCHAR(200)  NOT NULL,
    description VARCHAR(2000) NULL,
    price       NUMERIC(19,4) NOT NULL,
    category_id BIGINT        NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version     BIGINT        NOT NULL DEFAULT 0,

    -- Price must be strictly positive. Enforced here as well as in the DTO so
    -- the invariant survives a direct psql session or a future service.
    CONSTRAINT ck_products_price CHECK (price > 0),
    CONSTRAINT ck_products_name  CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_products_sku   CHECK (sku ~ '^[A-Z0-9][A-Z0-9-]{2,63}$')
);

-- SKU is the business key. Uniqueness here is the real guarantee; the service
-- pre-check only exists to produce a friendly 409 on the common path.
CREATE UNIQUE INDEX uq_products_sku ON products (sku);

-- "Products in this category", the most common catalogue filter. Partial on
-- `active` because inactive products are never listed publicly.
CREATE INDEX idx_products_category_active ON products (category_id, id) WHERE active = TRUE;

-- Price-range filtering within a category.
CREATE INDEX idx_products_price ON products (price) WHERE active = TRUE;

-- Case-insensitive name search. A trigram index (pg_trgm) would serve LIKE
-- '%term%' far better, but CREATE EXTENSION needs privileges the application
-- role deliberately lacks — so search is a prefix/substring scan over this
-- index, which is honest for a catalogue of this size. Noted in docs/ARCHITECTURE.md.
CREATE INDEX idx_products_name_lower ON products (lower(name));

-- ON DELETE RESTRICT above is deliberate: deleting a category that still has
-- products would orphan them or silently null their category. The API returns
-- 409 and asks the administrator to move or deactivate the products first.

COMMENT ON TABLE  products       IS 'Catalogue items. Price is the current list price, not what any order paid.';
COMMENT ON COLUMN products.price IS 'NUMERIC(19,4) — exact decimal. Never float. Order lines snapshot this value.';
COMMENT ON COLUMN products.sku   IS 'Stock-keeping unit; the stable business identifier. Unique across the catalogue.';
