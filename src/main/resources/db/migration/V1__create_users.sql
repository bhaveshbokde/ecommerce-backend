-- V1: application users.
--
-- Design notes
--  * BIGINT identity surrogate keys: compact, sequential, good B-tree locality.
--  * Email uniqueness is case-insensitive via a functional index rather than the
--    `citext` extension, because CREATE EXTENSION needs privileges the
--    least-privilege application role deliberately does not have.
--  * `role` is a single column rather than a user_roles join table. This
--    application has exactly two mutually-exclusive roles and no plans for more;
--    a join table would add a query and a mapping for no expressiveness gained.
--    If a user ever needed several roles at once, this becomes a join table.
--  * `version` backs JPA optimistic locking (@Version).
--  * All timestamps are TIMESTAMPTZ; the application works exclusively in UTC.

CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'ROLE_CUSTOMER',
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT ck_users_role  CHECK (role IN ('ROLE_CUSTOMER', 'ROLE_ADMIN')),
    CONSTRAINT ck_users_email CHECK (position('@' IN email) > 1)
);

-- Enforces "one account per email address" case-insensitively. This is the real
-- guarantee behind registration; the service-layer check is only there to turn
-- the common case into a friendly 409 instead of a constraint violation.
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

COMMENT ON TABLE  users               IS 'Registered customers and administrators.';
COMMENT ON COLUMN users.password_hash IS 'BCrypt hash (cost 10). Plain-text passwords are never stored, logged or returned.';
COMMENT ON COLUMN users.role          IS 'ROLE_CUSTOMER or ROLE_ADMIN. Public registration can only ever produce ROLE_CUSTOMER.';
COMMENT ON COLUMN users.version       IS 'Optimistic-locking version managed by Hibernate @Version.';
