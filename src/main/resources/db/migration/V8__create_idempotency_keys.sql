-- V8: idempotency records for checkout.
--
-- WHY CHECKOUT NEEDS THIS TOO
-- Payments are made idempotent by the unique index in V7, but checkout happens
-- *before* a payment exists. Without protection, a double-submitted checkout (an
-- impatient second click, or a client retrying a request whose response was lost)
-- creates two orders and reserves the stock twice.
--
-- HOW IT WORKS
-- The client sends an Idempotency-Key header. The service inserts a row here
-- inside the same transaction as the order. A duplicate request loses the insert
-- on the unique constraint and the stored response is replayed verbatim — the
-- caller receives the original 201 with the original order, and no second order
-- or reservation is created.
--
-- `request_hash` guards against key reuse with different content: the same key
-- sent with a genuinely different request is a client bug, and is rejected with
-- 422 rather than silently replaying an unrelated response.

CREATE TABLE idempotency_keys (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    idempotency_key VARCHAR(100) NOT NULL,
    endpoint        VARCHAR(100) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL,

    response_status INTEGER      NULL,
    response_body   TEXT         NULL,

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_idempotency_request_hash CHECK (request_hash ~ '^[0-9a-f]{64}$')
);

-- Scoped by user and endpoint: the same key on /orders and on /payments are
-- different operations and must not collide.
CREATE UNIQUE INDEX uq_idempotency_user_endpoint_key
    ON idempotency_keys (user_id, endpoint, idempotency_key);

-- Supports periodic purging of old records.
CREATE INDEX idx_idempotency_created ON idempotency_keys (created_at);

COMMENT ON TABLE  idempotency_keys               IS 'Replay protection for non-idempotent POSTs. The unique index is the guarantee.';
COMMENT ON COLUMN idempotency_keys.request_hash  IS 'SHA-256 of the canonical request body; detects key reuse with different content.';
COMMENT ON COLUMN idempotency_keys.response_body IS 'The original response, replayed verbatim to a duplicate request.';
