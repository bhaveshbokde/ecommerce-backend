-- V2: refresh tokens, stored so they can be revoked.
--
-- WHY THIS TABLE EXISTS
-- Access tokens here are stateless JWTs: fast to verify, impossible to revoke
-- before they expire. Refresh tokens are the opposite — they are long-lived, so
-- an un-revokable one is a serious liability. Storing them makes logout and
-- revocation real rather than advisory.
--
-- WHAT IS STORED
-- Only a SHA-256 hash of the token, never the token itself. A stolen database
-- dump therefore yields nothing usable: the attacker would need a preimage. This
-- is the same reasoning that applies to passwords, with one difference — a
-- refresh token is high-entropy random data, so a fast digest is sufficient and
-- BCrypt's deliberate slowness would only add latency to every refresh.

CREATE TABLE refresh_tokens (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMPTZ  NOT NULL,
    revoked_at TIMESTAMPTZ  NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_refresh_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

-- The lookup performed on every refresh request.
CREATE UNIQUE INDEX uq_refresh_tokens_hash ON refresh_tokens (token_hash);

-- "Revoke everything for this user" — used by logout-all and by a password change.
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id) WHERE revoked_at IS NULL;

-- Supports purging expired rows without scanning the whole table.
CREATE INDEX idx_refresh_tokens_expiry ON refresh_tokens (expires_at) WHERE revoked_at IS NULL;

COMMENT ON TABLE  refresh_tokens            IS 'Issued refresh tokens. Presence of a row is what makes a refresh token valid.';
COMMENT ON COLUMN refresh_tokens.token_hash IS 'SHA-256 hex of the token. The token itself is never persisted.';
COMMENT ON COLUMN refresh_tokens.revoked_at IS 'Set on logout or rotation. A revoked token is refused even before it expires.';
