-- V7: payment attempts against a simulated provider.
--
-- THIS IS A SIMULATION. No real payment network is contacted and no money moves.
-- The table is nevertheless modelled the way a real one would be, because the
-- interesting problems — idempotency, duplicate callbacks, out-of-order
-- callbacks, terminal-state protection — are identical either way.
--
-- IDEMPOTENCY
-- `idempotency_key` is supplied by the client and is unique per user. Two
-- identical POST /payments requests therefore cannot create two payment rows:
-- the second insert violates the unique index and the service returns the
-- existing payment instead. That is the whole mechanism — the guarantee lives in
-- the database, not in an application-level "have I seen this?" check, which
-- would race.
--
-- TERMINAL STATES
-- SUCCEEDED and FAILED are terminal. A callback arriving for a payment already
-- in a terminal state is acknowledged and ignored. This is what makes duplicate
-- and out-of-order provider callbacks safe, and it is enforced in the service
-- with the row locked (see PaymentService.handleCallback).

CREATE TABLE payments (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_reference  VARCHAR(64)   NOT NULL,
    order_id           BIGINT        NOT NULL REFERENCES orders (id) ON DELETE RESTRICT,
    user_id            BIGINT        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,

    status             VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    amount             NUMERIC(19,4) NOT NULL,
    currency           VARCHAR(3)    NOT NULL DEFAULT 'INR',

    idempotency_key    VARCHAR(100)  NOT NULL,
    provider_reference VARCHAR(100)  NULL,
    failure_reason     VARCHAR(255)  NULL,
    attempts           INTEGER       NOT NULL DEFAULT 0,

    completed_at       TIMESTAMPTZ   NULL,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version            BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT ck_payments_status CHECK (
        status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')
    ),
    CONSTRAINT ck_payments_amount   CHECK (amount > 0),
    CONSTRAINT ck_payments_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_payments_attempts CHECK (attempts >= 0)
);

-- Our own reference, returned to the client and quoted in support.
CREATE UNIQUE INDEX uq_payments_reference ON payments (payment_reference);

-- THE idempotency guarantee. Scoped per user so two customers may coincidentally
-- choose the same key without colliding.
CREATE UNIQUE INDEX uq_payments_user_idempotency ON payments (user_id, idempotency_key);

-- At most one payment that is not in a terminal failed state per order. A second
-- attempt is permitted only after the first has FAILED, which is what allows a
-- customer to retry a declined card without ever double-charging a succeeded one.
CREATE UNIQUE INDEX uq_payments_order_active
    ON payments (order_id)
    WHERE status IN ('PENDING', 'SUCCEEDED');

CREATE INDEX idx_payments_order ON payments (order_id);
CREATE INDEX idx_payments_user  ON payments (user_id, created_at DESC);

COMMENT ON TABLE  payments                    IS 'Payment attempts against a SIMULATED provider. No real money moves.';
COMMENT ON COLUMN payments.idempotency_key    IS 'Client-supplied. Unique per user — this index is what makes retries safe.';
COMMENT ON COLUMN payments.provider_reference IS 'Identifier returned by the simulated provider; a real gateway id in production.';
COMMENT ON INDEX  uq_payments_order_active    IS 'At most one PENDING or SUCCEEDED payment per order; retry allowed only after FAILED.';
