-- V6: orders and order lines.
--
-- PRICE SNAPSHOTS — the central requirement
-- order_items copies the product's sku, name and unit price at the moment of
-- purchase. Changing a product's price afterwards therefore cannot alter what an
-- existing order says it cost. Storing only product_id and joining to products
-- at read time would make every historical order silently re-price itself
-- whenever the catalogue changed — wrong for a receipt, and wrong for accounting.
--
-- It also means an order remains fully readable after a product is renamed, and
-- `line_total` is stored rather than computed so the arithmetic that produced the
-- order total is preserved exactly as it was applied.
--
-- ORDER STATUS vs PAYMENT STATUS
-- Two separate columns, because they are two separate lifecycles. An order can be
-- CREATED with payment PENDING, or CANCELLED with payment FAILED, or CONFIRMED
-- with payment SUCCEEDED. Collapsing them into one column would require a
-- combinatorial status enum and make illegal combinations expressible.

CREATE TABLE orders (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number   VARCHAR(32)   NOT NULL,
    user_id        BIGINT        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status         VARCHAR(20)   NOT NULL DEFAULT 'CREATED',
    payment_status VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    subtotal       NUMERIC(19,4) NOT NULL,
    total          NUMERIC(19,4) NOT NULL,
    currency       VARCHAR(3)    NOT NULL DEFAULT 'INR',
    cancelled_at   TIMESTAMPTZ   NULL,
    confirmed_at   TIMESTAMPTZ   NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version        BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT ck_orders_status CHECK (
        status IN ('CREATED', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED')
    ),
    CONSTRAINT ck_orders_payment_status CHECK (
        payment_status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')
    ),
    CONSTRAINT ck_orders_totals   CHECK (subtotal >= 0 AND total >= 0),
    CONSTRAINT ck_orders_currency CHECK (currency ~ '^[A-Z]{3}$')
);

-- ON DELETE RESTRICT on user_id: an account with order history cannot simply be
-- deleted out from under its orders. Deleting a customer is a deliberate process
-- (anonymise, or archive the orders first), not a cascade.

CREATE UNIQUE INDEX uq_orders_order_number ON orders (order_number);

-- "My order history, newest first." id DESC is the tiebreaker, so paging is
-- deterministic when several orders share a timestamp.
CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC, id DESC);

-- Administrative views: orders awaiting action.
CREATE INDEX idx_orders_status ON orders (status, created_at DESC);


CREATE TABLE order_items (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id    BIGINT        NULL REFERENCES products (id) ON DELETE SET NULL,

    -- Immutable purchase-time snapshot. These are the fields a receipt needs,
    -- and they must not change when the catalogue does.
    product_sku   VARCHAR(64)   NOT NULL,
    product_name  VARCHAR(200)  NOT NULL,
    unit_price    NUMERIC(19,4) NOT NULL,
    quantity      INTEGER       NOT NULL,
    line_total    NUMERIC(19,4) NOT NULL,

    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_order_items_quantity   CHECK (quantity > 0),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_order_items_line_total CHECK (line_total > 0)
);

-- product_id is nullable with ON DELETE SET NULL: deleting a product must not
-- delete the history of it having been sold. The snapshot columns keep the line
-- fully readable afterwards, which is exactly why they exist.

CREATE INDEX idx_order_items_order   ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id) WHERE product_id IS NOT NULL;

COMMENT ON TABLE  orders                    IS 'Customer orders. status and payment_status are independent lifecycles.';
COMMENT ON COLUMN orders.order_number       IS 'Human-facing identifier, unique. Safe to quote in support conversations.';
COMMENT ON TABLE  order_items               IS 'Order lines with immutable purchase-time price snapshots.';
COMMENT ON COLUMN order_items.unit_price    IS 'Price actually charged. A later catalogue change cannot alter it.';
COMMENT ON COLUMN order_items.line_total    IS 'unit_price * quantity, stored so the original arithmetic is preserved.';
